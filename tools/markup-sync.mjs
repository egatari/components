// The element and attribute list of components/markup-reader (Egatari spec §6.2 "Rendered output is data") is generated from
// the spec's normative schema/rendered-markup-1.json at the commit pinned in tools/spec.json, never edited by hand:
//   node tools/markup-sync.mjs           write the block into components/markup-reader/index.js
//   node tools/markup-sync.mjs --check   fail when the block differs from the schema (tools/test-markup-reader.mjs runs it too)
// The block is the schema without its $comment members, as one line of JSON (key order as in the schema).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, specFile, SPEC_PIN } from './spec.mjs';

export const SCHEMA = 'schema/rendered-markup-1.json';
export const FILE = path.join(ROOT, 'components', 'markup-reader', 'index.js');
const BEGIN = '// ---- BEGIN rendered-markup-1 (generated by tools/markup-sync.mjs from egatari-spec schema/rendered-markup-1.json; do not edit) ----';
const END = '// ---- END rendered-markup-1 ----';
const strip = (v) => Array.isArray(v) ? v.map(strip) : v && typeof v === 'object'
  ? Object.fromEntries(Object.entries(v).filter(([k]) => k !== '$comment' && k !== 'version').map(([k, x]) => [k, strip(x)])) : v;

export function schemaList() {
  const s = JSON.parse(specFile(SCHEMA));
  if (s.version !== 1) throw new Error(`${SCHEMA}: version ${s.version}, expected 1`);
  return strip(s);
}
export const blockOf = (list) => `${BEGIN}\nvar LIST = ${JSON.stringify(list)};\n${END}`;
export function embedded(js = fs.readFileSync(FILE, 'utf8')) {
  const a = js.indexOf(BEGIN), b = js.indexOf(END);
  if (a < 0 || b < a) throw new Error('components/markup-reader/index.js: no rendered-markup-1 block');
  return { a, b: b + END.length, text: js.slice(a, b + END.length) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const js = fs.readFileSync(FILE, 'utf8'), e = embedded(js), want = blockOf(schemaList());
  if (process.argv.includes('--check')) {
    if (e.text !== want) { console.log(`FAIL components/markup-reader: the rendered-markup-1 block differs from egatari-spec ${SPEC_PIN.commit.slice(0, 7)} ${SCHEMA} (node tools/markup-sync.mjs)`); process.exit(1); }
    console.log(`ok   components/markup-reader: the rendered-markup-1 block equals egatari-spec ${SPEC_PIN.commit.slice(0, 7)} ${SCHEMA}`);
  } else {
    fs.writeFileSync(FILE, js.slice(0, e.a) + want + js.slice(e.b));
    console.log(`markup-sync: wrote the block from egatari-spec ${SPEC_PIN.commit.slice(0, 7)} ${SCHEMA}`);
  }
}
