// The list of components (CATALOG.md), made from the frontmatter at the top of each components/<name>/README.md
//   node tools/catalog.mjs           rewrite CATALOG.md
//   node tools/catalog.mjs --check   only check that CATALOG.md is up to date (exit code 1 if not; npm test and CI)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, componentNames } from './studio.mjs';
import { frontmatter, list, purposeIds, SERIES_LABEL } from './lint.mjs';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const rows = [], byPurpose = new Map();
const ids = purposeIds(ROOT);
for (const name of componentNames()) {
  const f = frontmatter(fs.readFileSync(path.join(ROOT, 'components', name, 'README.md'), 'utf8'));
  if (!f) { console.warn(`no frontmatter: components/${name}/README.md`); continue; }
  const demo = fs.existsSync(path.join(ROOT, 'components', name, 'demo.html')) ? `[demo](components/${name}/demo.html)` : '—';
  list(f.purposes).forEach((p, i) => { if (!byPurpose.has(p)) byPurpose.set(p, []); byPurpose.get(p).push(i === 0 ? `**\`<${f.name}>\`**` : `\`<${f.name}>\``); });
  rows.push(`| [\`<${cell(f.name)}>\`](components/${name}/README.md) | ${cell(SERIES_LABEL[f.series] ? `${SERIES_LABEL[f.series]}（${f.series}）` : f.series)} | ${cell(f.summary)} | ${cell(f.steps)} | ${cell(list(f.purposes).join(', '))} | ${cell(list(f.variants).join(', ') || '—')} | ${cell(f.props)} | ${demo} |`);
}
const md = `# Components / 部品の一覧

Generated by \`node tools/catalog.mjs\` from the frontmatter of each \`components/<name>/README.md\`. Do not edit by hand.
\`node tools/catalog.mjs\` が各部品の README.md の先頭から作る。手で直さない。

| 部品 | 系列 | 内容 | 段階の数 | 言いたいこと | 見せ方 | 受け取る値 | 見本 |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## By purpose / 言いたいことから

From \`purposes.json\` (docs/conventions.md §4). Bold: the component's main purpose. Reserved: no component yet.
\`purposes.json\` から作る。太字はその部品の主な言いたいこと。予約は、まだ部品のないもの。

| id | 言いたいこと | Purpose | 既定の段階 | 部品 |
|---|---|---|---|---|
${[...ids.values()].map((p) => `| \`${p.id}\` | ${cell(p.ja)} | ${cell(p.en)} | ${cell(p.steps.ja)} | ${(byPurpose.get(p.id) || []).join(' ') || (p.reserved ? '（予約 / reserved）' : '—')} |`).join('\n')}
`;
const OUT = path.join(ROOT, 'CATALOG.md');
if (process.argv.includes('--check')) {
  // line endings are not compared (git on Windows may check out CRLF)
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === md;
  console.log(same ? `CATALOG.md is up to date (${rows.length} components)` : 'CATALOG.md is out of date: run node tools/catalog.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, md);
console.log(`CATALOG.md: ${rows.length} components`);
