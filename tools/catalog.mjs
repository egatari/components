// The list of components (CATALOG.md), made from the frontmatter at the top of each components/<name>/README.md
//   node tools/catalog.mjs           rewrite CATALOG.md
//   node tools/catalog.mjs --check   only check that CATALOG.md is up to date (exit code 1 if not; npm test and CI)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, componentNames, libraryNames } from './studio.mjs';
import { frontmatter, list, purposeIds, SERIES_LABEL, flags, TIERS, TIER_LABEL, SETS, SET_LABEL } from './lint.mjs';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const rows = [], byPurpose = new Map(), byTier = new Map();
// 段（tier）: 標準・専門（束）・特殊 (tools/lint.mjs TIER_LABEL, SET_LABEL)
const tierText = (f) => (TIER_LABEL[f.tier] || f.tier || '') + (f.set ? `（${SET_LABEL[f.set] || f.set}）` : '');
const ids = purposeIds(ROOT);
for (const name of componentNames()) {
  const f = frontmatter(fs.readFileSync(path.join(ROOT, 'components', name, 'README.md'), 'utf8'));
  if (!f) { console.warn(`no frontmatter: components/${name}/README.md`); continue; }
  const fl = flags(fs.readFileSync(path.join(ROOT, 'components', name, 'index.js'), 'utf8'));
  const demo = fs.existsSync(path.join(ROOT, 'components', name, 'demo.html')) ? `[demo](components/${name}/demo.html)` : '—';
  list(f.purposes).forEach((p, i) => { if (!byPurpose.has(p)) byPurpose.set(p, []); byPurpose.get(p).push(i === 0 ? `**\`<${f.name}>\`**` : `\`<${f.name}>\``); });
  const key = f.tier === 'specialized' ? `specialized:${f.set}` : f.tier;
  if (!byTier.has(key)) byTier.set(key, []);
  byTier.get(key).push(`\`<${f.name}>\`` + (f.display ? `（${f.display}）` : ''));
  rows.push(`| [\`<${cell(f.name)}>\`](components/${name}/README.md)${f.display ? ` ${cell(f.display)}` : ''}${fl.interactive ? ' 「操作できる」' : ''}${fl.group === 'tool' ? ' 「道具」' : ''} | ${cell(tierText(f))} | ${cell(SERIES_LABEL[f.series] ? `${SERIES_LABEL[f.series]}（${f.series}）` : f.series)} | ${cell(f.summary)}${fl.viewerInput ? '（入力あり）' : ''} | ${cell(f.steps)} | ${cell(list(f.purposes).join(', '))} | ${cell(list(f.variants).join(', ') || '—')} | ${cell(f.props)} | ${demo} |`);
}
const md = `# Components / 部品の一覧

Generated by \`node tools/catalog.mjs\` from the frontmatter of each \`components/<name>/README.md\`. Do not edit by hand.
\`node tools/catalog.mjs\` が各部品の README.md の先頭から作る。手で直さない。

| 部品 | 段 | 系列 | 内容 | 段階の数 | 伝えたいこと | 見せ方 | 受け取る値 | 見本 |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## By tier / 段から

Standard (標準): offered for every lesson. Specialized (専門): offered by set when the scene or the title calls for it. Extra (特殊):
not offered; used when a lesson clearly needs one (read its README). The set is how specialized parts are loaded and evaluated together.
標準はどの教材にも出す道具。専門は場面やタイトルから束ごとにすすめる。特殊は一覧に出さず、材料がはっきり要るときに README を読んで使う。

| 段 | 束 | 部品 |
|---|---|---|
${[...TIERS.flatMap((t) => (t === 'specialized' ? SETS.map((x) => [t, x, `specialized:${x}`]) : [[t, null, t]]))].filter(([, , k]) => byTier.has(k)).map(([t, x, k]) => `| ${TIER_LABEL[t]} | ${x ? SET_LABEL[x] : '—'} | ${byTier.get(k).join(' ')} |`).join('\n')}

## Library parts / ライブラリのパーツ

Components 2.0 (alpha, not for lessons yet): parts other parts require (Egatari spec §6.1). They define no element and are not written by authors.
2.0 の準備中（まだ教材には使わない）。ほかのパーツが使うパーツ。要素を作らず、作者が直接は書かない。

| パーツ | 版 | 内容 | 使うパーツ |
|---|---|---|---|
${libraryNames().map((name) => { const f = frontmatter(fs.readFileSync(path.join(ROOT, 'components', name, 'README.md'), 'utf8')) || {}; return `| [\`${cell(name)}\`](components/${name}/README.md) | ${cell(f.version)} | ${cell(f.summary)} | ${cell(f.requires || '—')} |`; }).join('\n')}

## By purpose / 伝えたいことから

From \`purposes.json\` (docs/conventions.md §4). Bold: the component's main purpose. Reserved: no component yet.
\`purposes.json\` から作る。太字はその部品の主な伝えたいこと。予約は、まだ部品のないもの。

| id | 伝えたいこと | Purpose | 既定の段階 | 部品 |
|---|---|---|---|---|
${[...ids.values()].map((p) => `| \`${p.id}\` | ${cell(p.ja)} | ${cell(p.en)} | ${cell(p.steps.ja)} | ${(byPurpose.get(p.id) || []).join(' ') || (p.reserved ? '（予約 / reserved）' : '—')} |`).join('\n')}
`;
const OUT = path.join(ROOT, 'CATALOG.md');
if (process.argv.includes('--check')) {
  // line endings are not compared (git on Windows may check out CRLF)
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === md;
  console.log(same ? `CATALOG.md is up to date (${rows.length} components)` : 'CATALOG.md is out of date: run node tools/catalog.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, md);
console.log(`CATALOG.md: ${rows.length} components`);
