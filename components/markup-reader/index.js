// markup-reader 1.0.0: the reader of build-time rendered markup (Egatari spec §6.2 "Rendered output is data"), a library part
// (spec §6.1). Parts that show what the producer rendered (KaTeX's HTML and MathML, abcjs's SVG) insert it only through this
// reader, never as HTML: a small parser of its own (no innerHTML, no DOMParser, no browser parser at all) that creates each
// element in its namespace (HTML, SVG, MathML) with createElementNS and sets only what egatari-spec's
// schema/rendered-markup-1.json (normative) admits:
//   - an element listed for its namespace, else the element is dropped with its subtree;
//   - an attribute listed for the element or globally for its namespace ("data-*" is a prefix), with the value grammar the
//     schema gives for it (id, data-*, fill, stroke), else the attribute is dropped;
//   - style only as the listed properties with a length or a listed keyword, each set with style.setProperty (never color);
//   - xmlns is the namespace declaration of serialised markup, not an attribute: it must name the namespace the reader
//     creates the element in (else the element is dropped) and is never set;
//   - text is kept (as text nodes; &amp; &lt; &gt; &quot; &apos; &#n; &#xh; decoded); comments, doctypes, CDATA and
//     processing instructions are dropped.
// Everything dropped is listed in what read() returns, and a part reports it once (sink below, ctx.report("data", …)).
// The list is not edited here: it is the generated block below (node tools/markup-sync.mjs writes it from the spec's schema at
// the commit pinned in tools/spec.json; tools/test-markup-reader.mjs checks that it equals the schema). Additions are made in
// the spec, never in a reader.
//
// It returns {read, texFrame, sink, LIST}:
//   read(markup, parent, ns)   parse markup and append what is admitted to parent; ns is the namespace of parent's content
//                              ("html" by default, "svg", "mathml"). Returns the list of what was dropped (strings), [] when
//                              nothing was.
//   texFrame(parent, x, y, item, key, o, sk)   a formula in an SVG figure, from the producer's output item[key + "Html"]
//                              (spec §6.2: e.g. texHtml beside tex), framed as Egatari Studio's kit/deck.js did at play time:
//                              a foreignObject (class smath) holding an inline-block div of size o.size and colour o.color,
//                              placed so that x is the anchor (start, middle, end) and y the baseline. Without rendered
//                              output (a file built without the renderer, a tier A edit), the div shows item[key] as plain
//                              text (spec §6.2 Missing output) and sk.missing reports it. Returns the foreignObject.
//   sink(part, ctx)            {missing(src), dropped(src, list)}: reports through ctx.report("data", "[<name>] …") at most once
//                              of each kind per element (spec §6.2: reported once), <name> = the tag without m- (the part's name).
//
// Provenance of texFrame: the frame that the math-in-SVG function of Egatari Studio's kit/deck.js (DECK.svg + Math; the name is not written here, because
// that Studio build loads KaTeX at play time for any component code that names it) drew (https://github.com/egatari/egatari-studio,
// commit 03eaf0607598b993eb020f8e619caa53526bc771), MIT License, Copyright (c) 2026 Gendo Kumoi, the same owner and licence as
// this repository; KaTeX's render call there is replaced by read() of the producer's output.
